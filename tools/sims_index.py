#!/usr/bin/env python3
"""Regenerate tests/SIMS.md from the `# args:` line under each case in tests/sims.gd (M6.0l).
TEST sims_index fails when the two drift."""
import re, sys
src = open('tests/sims.gd').read().split('\n')
rows = []
for i, line in enumerate(src):
    m = re.match(r'^        "([A-Za-z0-9_]+)":\s*$', line)
    if m:
        nxt = src[i + 1].strip() if i + 1 < len(src) else ''
        args = nxt[len('# args:'):].strip() if nxt.startswith('# args:') else '(missing)'
        rows.append((m.group(1), args))
text = "# Sims index - `tools/sim.sh NAME ARGS`; generated by tools/sims_index.py from the `# args:` line under each case in tests/sims.gd (TEST sims_index checks it)\n\n| sim | args |\n|---|---|\n"
for n, a in rows:
    text += "| %s | `%s` |\n" % (n, a.replace('|', '\\|'))
if '--check' in sys.argv:
    cur = open('tests/SIMS.md').read()
    sys.exit(0 if cur == text else 1)
open('tests/SIMS.md', 'w').write(text)
print("SIMS.md: %d cases" % len(rows))
